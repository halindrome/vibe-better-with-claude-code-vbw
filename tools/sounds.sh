#!/usr/bin/env bash
# Writes plugin/hooks/panel-sounds.js: the list of the sounds shipped in
# plugin/assets/audio/<character>/*.mp3 (D109). Claude Code lists folders only
# relative to the project, so the panel reads this generated list instead.
# Sorted, mp3 files only (no .DS_Store), character folders with no sounds skipped.
# Run it after adding or removing a sound.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/plugin/hooks/panel-sounds.js"

{
  echo "// Generated by tools/sounds.sh from plugin/assets/audio/<character>/*.mp3. Do not edit."
  echo "export const SOUNDS = ["
  (cd "$ROOT/plugin" && find assets/audio -mindepth 2 -maxdepth 2 -type f -name '*.mp3' | LC_ALL=C sort) |
    while IFS= read -r f; do echo "  '$f',"; done
  echo "]"
  cat <<'JS'

// The sound to play for record.settings.sound: 'off' is none; a folder name is a random
// sound of that folder; unset, 'default' or a folder that is gone is a random sound of all.
export function soundFor(choice, random = Math.random) {
  if (choice === 'off') return null
  const own = SOUNDS.filter((s) => s.startsWith('assets/audio/' + choice + '/'))
  const from = own.length ? own : SOUNDS
  return from.length ? { asset: from[Math.floor(random() * from.length)] } : null
}
JS
} > "$OUT"
